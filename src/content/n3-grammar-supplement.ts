export const n3GrammarSupplement: readonly GrammarEntry[] = rows.map(([pattern, meaning, formation, explanation, example, translation, focus], index) => {
  const distractors: string[] = [];
  for (let offset = 1; distractors.length < 3; offset++) {
    const candidate = meanings[(index + offset * 17) % meanings.length];
    if (candidate !== meaning && !distractors.includes(candidate)) distractors.push(candidate);
  }
  const choices = [...distractors];
  choices.splice(index % 4, 0, meaning);
  return {
    pattern, meaning, formation, explanation, example, translation, focus,
    furigana: focusReadings[focus] ? example.replace(focus, `{${focus}|${focusReadings[focus]}}`) : undefined,
    question: {
      kind: '문맥 속 문법',
      prompt: `다음 문장에서 「${pattern}」의 뜻을 고르세요.\n${example}`,
      choices: choices as [string, string, string, string],
      answer: meaning,
      explanation: `${pattern}: ${explanation}\n${translation}`,
    },
  };
});
