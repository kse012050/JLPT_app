type Draft = { kind: string; prompt: string; answer: string; distractors: [string, string, string]; explanation: string };

function makeQuestion(draft: Draft, index: number): ChoiceQuestion {
  const choices = [...draft.distractors];
  choices.splice(index % 4, 0, draft.answer);
  return { kind: draft.kind, prompt: draft.prompt, answer: draft.answer, choices: choices as [string, string, string, string], explanation: draft.explanation };
}

function checkedWord(word: string, reading: string) {
  const entry = bankByLevel.N3.find((item) => item.word === word && item.reading === reading);
  if (!entry) throw new Error(`N3 참고 어휘에서 찾을 수 없습니다: ${word} · ${reading}`);
  return entry;
}

function reading(word: string, kana: string, distractors: [string, string, string]): Draft {
  const entry = checkedWord(word, kana);
  return { kind: '한자 읽기', prompt: `「${word}」의 읽기로 맞는 것을 고르세요.`, answer: kana, distractors, explanation: `「${word}」의 읽기는 ${kana}입니다. 뜻: ${entry.meaningKo}.` };
}

function orthography(kana: string, word: string, distractors: [string, string, string]): Draft {
  const entry = checkedWord(word, kana);
  return { kind: '표기', prompt: `「${kana}」의 표기로 맞는 것을 고르세요.`, answer: word, distractors, explanation: `${kana}의 표기는 「${word}」입니다. 뜻: ${entry.meaningKo}.` };
}

function draft(kind: string, prompt: string, answer: string, distractors: [string, string, string], explanation: string): Draft {
  return { kind, prompt, answer, distractors, explanation };
}

